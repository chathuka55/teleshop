#!/usr/bin/env node
/**
 * pnpm brand-logos — writes src/config/brand-logos.ts from Simple Icons (CC0 SVG paths of the
 * official logos; the marks themselves stay trademarks of their owners). Only the brands listed
 * here end up in the app bundle, never the whole icon set. Re-run after adding a brand.
 * Brands without an icon (or added later by an admin) show their name as a wordmark instead.
 */
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";
import { svgPathBbox } from "svg-path-bbox";

/** Our brand slug (brands.slug) → Simple Icons slug. */
const BRANDS = {
  apple: "apple",
  samsung: "samsung",
  xiaomi: "xiaomi",
  asus: "asus",
  dell: "dell",
  hp: "hp",
  lenovo: "lenovo",
  sony: "sony",
  jbl: "jbl",
  msi: "msi",
  huawei: "huawei",
  google: "google",
  amd: "amd",
  corsair: "corsair",
  "tp-link": "tplink",
  logitech: "logitech",
  nothing: "nothing",
  oneplus: "oneplus",
  acer: "acer",
  nvidia: "nvidia",
  intel: "intel",
  razer: "razer",
  oppo: "oppo",
  vivo: "vivo",
  realme: "realme",
  honor: "honor",
};

/** Hover colour: the brand's own, unless it is too dark to read on our near-black background. */
function hoverColor(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const luminance = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
  return luminance < 0.06 ? null : `#${hex}`;
}

const rows = [];
const missing = [];
for (const [brand, slug] of Object.entries(BRANDS)) {
  const icon = icons[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
  if (!icon) {
    missing.push(brand);
    continue;
  }
  const color = hoverColor(icon.hex);
  // Crop to the drawing itself: Simple Icons centre every logo in 24×24, so a wide wordmark is a
  // thin strip with empty space above and below. A tight box lets each logo fill its tile evenly.
  const [x0, y0, x1, y1] = svgPathBbox(icon.path);
  const r = (n) => Math.round(n * 1000) / 1000;
  const viewBox = [x0, y0, x1 - x0, y1 - y0].map(r).join(" ");
  rows.push(
    `  ${JSON.stringify(brand)}: { title: ${JSON.stringify(icon.title)}, viewBox: ${JSON.stringify(viewBox)}, path: ${JSON.stringify(icon.path)}, color: ${color ? JSON.stringify(color) : "null"} },`,
  );
}

const out = `/* Generated by scripts/dev/brand-logos.mjs from Simple Icons (CC0) — do not edit by hand. */
/* Logos are trademarks of their owners, shown only to say which brands the shops sell. */

export type BrandLogo = {
  title: string;
  /** Tight box around the drawing ("x y width height"). */
  viewBox: string;
  /** SVG path data (Simple Icons' 24×24 coordinates). */
  path: string;
  /** Hover colour (the brand's own), or null when it is too dark for the dark theme. */
  color: string | null;
};

export const brandLogos: Readonly<Record<string, BrandLogo>> = {
${rows.join("\n")}
};
`;
writeFileSync("src/config/brand-logos.ts", out);
console.log(
  `brand-logos.ts: ${rows.length} logos${missing.length ? ` · no icon for: ${missing.join(", ")}` : ""}`,
);
